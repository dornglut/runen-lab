#!/usr/bin/env python3
"""Tiny restricted change-program compiler, NOT an arbitrary Rust compiler.

The output is deterministic and carries all the generated reverse-key
maintenance and fanout propagation for one declared keyed foreign-key join.
"""
import argparse
import json
import re
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent
p = argparse.ArgumentParser()
p.add_argument('--rule', type=Path, default=ROOT/'rule.json')
p.add_argument('--output', type=Path, default=ROOT.parent/'src'/'generated.rs')
p.add_argument('--check', action='store_true')
a = p.parse_args()
rule = json.loads(a.rule.read_text())
expected = {
    'name': 'render_packets',
    'input': 'object',
    'join': 'material',
    'foreign_key': 'material',
    'output': 'packet',
}
if rule != expected:
    raise ValueError('unsupported rule: this prototype generates only render_packets')
if any(not isinstance(v, str) or not re.fullmatch('[A-Za-z_][A-Za-z_0-9]*', v) for v in rule.values()):
    raise ValueError('invalid identifiers')
body = '''//! GENERATED by tools/compile_rule.py; do not edit.
//! Supports a single keyed foreign-key join, not general differential Rust.
use crate::contract::{Key, Obj};
use std::collections::{BTreeMap, BTreeSet};

pub fn update_inverse(
    index: &mut BTreeMap<u32, BTreeSet<Key>>,
    before: Option<(Key, Obj)>,
    after: Option<(Key, Obj)>,
) {
    if let (Some((old_key, old)), Some((new_key, new))) = (before, after) {
        if old_key == new_key && old.material == new.material { return; }
    }
    if let Some((key, old)) = before {
        if let Some(users) = index.get_mut(&old.material) {
            users.remove(&key);
            if users.is_empty() { index.remove(&old.material); }
        }
    }
    if let Some((key, new)) = after {
        index.entry(new.material).or_default().insert(key);
    }
}

pub fn snapshot_groups(
    index: &BTreeMap<u32, BTreeSet<Key>>,
    changed_materials: &BTreeSet<u32>,
) -> BTreeMap<u32, BTreeSet<Key>> {
    changed_materials.iter().filter_map(|material| {
        index.get(material).map(|group| (*material, group.clone()))
    }).collect()
}

pub fn affected(
    index_before: &BTreeMap<u32, BTreeSet<Key>>,
    index_after: &BTreeMap<u32, BTreeSet<Key>>,
    changed_objects: &BTreeSet<Key>,
    changed_materials: &BTreeSet<u32>,
) -> BTreeSet<Key> {
    let mut keys = changed_objects.clone();
    for material in changed_materials {
        if let Some(users) = index_before.get(material) {
            keys.extend(users.iter().copied());
        }
        if let Some(users) = index_after.get(material) {
            keys.extend(users.iter().copied());
        }
    }
    keys
}
'''
# Compare the generated source in its rustfmt-normalized form: Cargo's
# formatter owns the checked-in representation of generated Rust.
with tempfile.TemporaryDirectory() as directory:
    scratch = Path(directory) / 'generated.rs'
    scratch.write_text(body, encoding='utf-8')
    subprocess.run(['rustfmt', '--edition', '2024', str(scratch)], check=True)
    formatted = scratch.read_text(encoding='utf-8')

if a.check:
    if not a.output.exists() or a.output.read_text(encoding='utf-8') != formatted:
        raise SystemExit('generated Rust is stale')
else:
    a.output.write_text(formatted, encoding='utf-8')
